#!/usr/bin/env python3
"""Embed DocC Markdown from the Quiver revision recorded in Package.resolved."""

import argparse
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
CATALOG = "Sources/Quiver/Docs/Quiver.docc"
OUTPUT = ROOT / "Sources/QuiverMCP/Core/_QuiverDocCorpus.swift"
HEADING = re.compile(r"^ {0,3}(#{1,6})\s+(.+?)\s*#*\s*$")
FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")


def sections(markdown):
    lines = markdown.splitlines()
    headings = []
    path = []
    fence = None
    for index, line in enumerate(lines):
        marker = FENCE.match(line)
        if fence:
            if marker and marker[1].startswith(fence) and not marker[2].strip():
                fence = None
            continue
        if marker:
            fence = marker[1]
            continue
        heading = HEADING.match(line)
        if heading:
            level = len(heading[1])
            path = [(depth, title) for depth, title in path if depth < level]
            path.append((level, heading[2]))
            headings.append((index, " / ".join(title for depth, title in path if depth > 1)))

    if not headings:
        return
    title = HEADING.match(lines[headings[0][0]])[2]
    for (start, heading), (end, _) in zip(headings, headings[1:] + [(len(lines), "")]):
        body = "\n".join(lines[start + 1:end]).strip()
        if body:
            yield start + 1, max(start + 1, end), title, heading, body


def generate(pin):
    state = pin["state"]
    checkout = ROOT / ".build/checkouts/quiver"
    archive = subprocess.check_output(["git", "-C", checkout, "archive", state["revision"], CATALOG])
    source = f'{pin["location"].removesuffix(".git")}/blob/{state["revision"]}'
    entries = []
    with tarfile.open(fileobj=io.BytesIO(archive)) as tree:
        for item in sorted(tree.getmembers(), key=lambda member: member.name):
            if not item.isfile() or not item.name.endswith(".md") or item.name.startswith(f"{CATALOG}/Resources/"):
                continue
            slug = item.name.removeprefix(CATALOG + "/").removesuffix(".md")
            markdown = tree.extractfile(item).read().decode("utf-8")
            for start, end, title, heading, body in sections(markdown):
                entries.append(dict(
                    id=f"{slug}:{start}", title=title, heading=heading, markdown=body,
                    source=f"{source}/{quote(item.name)}#L{start}-L{end}",
                ))
    if not entries:
        raise SystemExit("No Quiver DocC sections found")
    payload = json.dumps(entries, ensure_ascii=True, separators=(",", ":"))
    # JSON escapes each field. A raw Swift literal preserves those escapes.
    delimiter = "#" * 4
    while f'"""{delimiter}' in payload or f"\\{delimiter}" in payload:
        delimiter += "#"
    return (
        "// Generated by Scripts/generate-quiver-docs.py. Do not edit.\n"
        "// Quiver documentation is distributed under the Apache License 2.0.\n\n"
        "enum _QuiverDocCorpus {\n"
        f'    static let version = "{state["version"]}"\n'
        f'    static let json = {delimiter}"""\n{payload}\n"""{delimiter}\n'
        "}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the committed corpus is current")
    args = parser.parse_args()
    pins = json.loads((ROOT / "Package.resolved").read_text())["pins"]
    pin = next(pin for pin in pins if pin["identity"] == "quiver")
    corpus = generate(pin)
    if args.check:
        if OUTPUT.read_text() != corpus:
            raise SystemExit("Embedded DocC differs from Package.resolved. Regenerate the corpus.")
    else:
        OUTPUT.write_text(corpus)


if __name__ == "__main__":
    main()
